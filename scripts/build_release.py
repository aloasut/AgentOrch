#!/usr/bin/env python3
"""Build the generic distribution zip for the Agent-Orchestration kit.

The set of packaged files is not maintained here: it is *derived* from the
`REQUIRED` list inside scripts/validate_kit.py, which is the single source of
truth for both (1) this repository's structurally required files and (2) the
release package manifest. The per-project config is NOT packaged: downstream
copies kit/templates/project.md to docs/PROJECT.md and fills it in, so a
released kit always ships the unfilled FILL_IN template.

Archived bytes are normalized to LF line endings first. A payload is treated as
text when it contains no NUL byte and decodes as UTF-8; every CRLF in such a
payload is folded to LF, while binary payloads ship verbatim. This is required
for byte-level reproducibility: one and the same committed tree can be checked
out with different line endings (a fresh Windows worktree under
`core.autocrlf=true` turns LF blobs into CRLF), which would otherwise change the
packaged bytes and therefore the zip SHA256 between two checkouts of one commit.

Two naming modes exist, and they never combine:

* default (date) build: `agentorch-YYYYMMDD.zip` with the top-level directory
  `agentorch-YYYYMMDD/`, stamped by `--date` or by today's date. CI keeps
  calling the builder with no arguments, so this mode stays the default.
* public release build: `--release-version 1.6` produces `AgentOrch-1.6.zip`
  with the top-level directory `AgentOrch-1.6/`, i.e. the archive stem and the
  top-level directory are the same string in both modes. Pass the version
  without a `v` prefix (the tag is `v1.6`, the asset is `AgentOrch-1.6.zip`).
  `--date` and `--release-version` are mutually exclusive; passing both is a
  build error rather than a silent precedence rule.

The release name only changes the asset / top-level directory. The packaged file
set, the manifest schema, and the `format_version` recorded in `MANIFEST.json`
are identical in both modes: a public release number is not a Format version.

A mandatory self-check runs after packaging. There is deliberately no flag to
skip it. On any failure the script prints `RELEASE SELF-CHECK FAILED`, follows it
with one line per reason, and exits with a non-zero status.

The package also carries a machine-readable `MANIFEST.json` (suite name, format
version, manifest schema version, and one entry per shipped file with its
category, SHA-256 and size). The manifest is generated by
scripts/check_drift.py, which owns the single classification rule; this builder
imports it instead of restating the rule. The manifest has no timestamp and its
entries are sorted, so the same tree always produces the same manifest bytes.

Self-checks (see release/README.md for the published standard):
  a. packaged file set == validate_kit.REQUIRED + MANIFEST.json (count and names
     must match), and MANIFEST.json resolves every path, matches every hash and
     size, and uses only legal categories
  b. inside the extracted archive: `validate_kit.py` exits 0 (which also
     re-validates MANIFEST.json there)
  c. inside the extracted archive: `validate_kit.py --project-ready` is EXPECTED
     TO FAIL (exit 1, output mentions FILL_IN); a pass means the template was not
     applied and is reported as an error
  d. inside the extracted archive: `python -m unittest discover -s tests` exits 0
  e. inside the extracted archive: `orchestrator.py init` and
     `orchestrator.py task list` exit 0 (smoke; init creates a throwaway
     .orchestration/ in the temp extraction, which is expected)
  f. non-essential information scan: zero hits over every text file in the
     package (personal paths, credential traces, and forbidden structure), plus
     any extra literal supplied by this machine (see below). The same pass also
     asserts that no packaged *text* file contains CRLF: packaged text is folded
     to LF before archiving (see normalize_line_endings), so a surviving CRLF
     means normalization missed a file and reproducibility across checkouts is
     no longer guaranteed.
  i. inside the extracted archive: `python -m scripts.update_agentorch.entry
     --help` imports the natural-language entry and exits 0.
  j. inside the extracted archive: `templates/self-improvement/sources.example.json`
     is a registry the shipped `scripts/self_improvement/sources.py` accepts.
  k. inside the extracted archive: `python scripts/run_delivery_scenarios.py --json`
     exits 0, reports `errors: 0`, every negative scenario passed (its gate really
     fired) and at least one positive control passed.
  l. inside the extracted archive: `python scripts/report_metrics.py --gold-sample
     --since ... --until ... --json` reports seven metrics with a window, sample
     size, missing rate and coverage, and the same script reports an empty input
     as `no data` (never 0).
  h. inside the extracted archive: `scripts/architecture/check.py` exits 0 with
     a JSON report marked `enforcement_mode: OFF` and `blocking: false` (the
     package ships no contract, so the checker must degrade to read-only
     diagnosis instead of guessing boundaries or failing)
  g. final manifest: package file count, zip path, zip size in bytes, SHA256

Scan patterns are layered on purpose. FORBIDDEN_PATTERNS holds only *generic*
rules that are meaningful for every clone (home-directory paths, credential
prefixes); it must stay free of anything tied to one machine or one repository
(a username, an absolute checkout path, this repository's task IDs, repo-only
document names). Machine- and repository-specific additions live outside the
repository, in `.local/release-scan.json`, which is git-ignored and never
shipped. That keeps this file publishable while a local clone can still enforce
its stricter rules. If the file is absent the build simply runs with the generic
rules and says so.

Only the standard library is used and every child process is launched with
sys.executable (never a bare `python`).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
import zipfile
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VALIDATOR = ROOT / 'scripts' / 'validate_kit.py'
PROJECT_TEMPLATE = ROOT / 'templates' / 'project.md'
PROJECT_CONFIG = 'docs/PROJECT.md'  # project-owned; never packaged (docs/ is forbidden)
DEFAULT_OUTPUT_DIR = 'release'

# The archive stem doubles as the single top-level directory inside the zip.
DATE_ASSET_PREFIX = 'agentorch-'
RELEASE_ASSET_PREFIX = 'AgentOrch-'
DATE_STAMP_RE = re.compile(r'\d{8}')
# 1.6 and 1.6.1 are accepted; a 'v' prefix is not (that is the git tag, not the
# asset name), and neither are prerelease suffixes.
RELEASE_VERSION_RE = re.compile(r'\d+\.\d+(?:\.\d+)?')

# check_drift.py owns manifest generation, file classification and byte
# normalization. It sits next to this script (and is shipped, while this builder
# is not), so importing it from the script directory keeps one implementation.
sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_drift  # noqa: E402  (path bootstrap above)

MANIFEST_NAME = check_drift.MANIFEST_NAME
normalize_line_endings = check_drift.normalize_line_endings
is_text = check_drift.is_text

# Generic literal substrings that must never appear in a distributed package.
# Matching is exact (plain substring, not a broad regex). Everything here has to
# be meaningful for *any* clone: this file is itself published, so a username, an
# absolute checkout path or one repository's task IDs would leak exactly what the
# scan exists to prevent. Machine-specific additions belong in
# .local/release-scan.json (see load_extra_patterns) and stay out of git.
FORBIDDEN_PATTERNS = [
    # personal home directories (generic forms, no usernames)
    'C:/Users/',
    'C:\\Users\\',
    '/Users/',
    # credential traces (literal prefixes; the bare 'sk-' prefix needs a shape
    # regex instead, see FORBIDDEN_REGEXES below)
    'ghp_',
    'github_pat_',
    '-----BEGIN',
    'AKIA',
]

# Credential prefixes that must NOT be matched as a bare substring. An OpenAI-style
# key is "sk-" followed by a long run of key characters. Matching the bare
# substring 'sk-' would also flag ordinary English words such as "task-id",
# "risk-based", "subtask-level" or "disk-based", which would abort normal releases.
# Match the key shape instead: a word boundary, then "sk-", then at least 16 key
# characters. Do NOT revert this to a bare 'sk-' substring.
FORBIDDEN_REGEXES = [
    ('sk-<openai-style key>', re.compile(r'\bsk-[A-Za-z0-9_-]{16,}')),
]

# Path segments that must never exist inside the package (belt and braces on top
# of check a, which already pins the file set to REQUIRED).
FORBIDDEN_SEGMENTS = frozenset({'.orchestration', 'release', 'docs', '.worktrees', '.workbuddy', '.git'})
FORBIDDEN_PATHS = frozenset({'scripts/build_release.py'})

# Optional per-machine / per-repository additions. Git-ignored (.gitignore keeps
# only .local/README.md) and never packaged, so a strict local rule such as a
# username or an absolute checkout path never enters the published tree.
LOCAL_SCAN_FILE = ROOT / '.local' / 'release-scan.json'
LOCAL_SCAN_LABEL = '.local/release-scan.json'


def read_required():
    """Extract the REQUIRED list from scripts/validate_kit.py (the only manifest)."""
    source = VALIDATOR.read_text(encoding='utf-8')
    match = re.search(r'REQUIRED\s*=\s*\[(.*?)\]', source, re.S)
    if not match:
        raise SystemExit('build error: could not locate the REQUIRED list in scripts/validate_kit.py')
    items = re.findall(r"'([^']+)'|\"([^\"]+)\"", match.group(1))
    required = [single or double for single, double in items]
    if not required:
        raise SystemExit('build error: REQUIRED list is empty')
    if len(set(required)) != len(required):
        raise SystemExit('build error: REQUIRED list contains duplicate entries')
    return required


def collect_sources(required):
    """Return {relative_path: bytes} for every file that should ship.

    The per-project config is intentionally NOT shipped: docs/ is a forbidden
    segment, so downstream copies kit/templates/project.md to docs/PROJECT.md
    and fills it in (self-check c proves --project-ready fails until they do).
    """
    files = {}
    for rel in required:
        source = ROOT / rel
        if not source.is_file():
            raise SystemExit(f'build error: required source missing: {source}')
        files[rel] = normalize_line_endings(source.read_bytes())
    return files


# Fixed metadata for every archive entry so repeated builds are byte-identical.
# ZipFile.writestr(name, data) would otherwise stamp the *current* time, making
# the zip's SHA256 change on every run and defeating the SHA256 recorded in the
# release list. A fixed timestamp (the classic 1980-01-01 DOS epoch), an explicit
# regular-file mode and an explicit create_system keep the bytes independent of
# build time and platform.
ZIP_ENTRY_TIME = (1980, 1, 1, 0, 0, 0)
ZIP_ENTRY_ATTR = 0o644 << 16
ZIP_CREATE_SYSTEM = 3  # 3 == Unix; keeps external_attr semantics stable


def write_zip(zip_path, files, top_dir):
    zip_path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as archive:
        for rel in sorted(files):
            info = zipfile.ZipInfo(filename=f'{top_dir}/{rel}', date_time=ZIP_ENTRY_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = ZIP_ENTRY_ATTR
            info.create_system = ZIP_CREATE_SYSTEM
            archive.writestr(info, files[rel])


def load_extra_patterns():
    """Return the extra forbidden literals from .local/release-scan.json.

    The file is optional: a clone without it builds with the generic rules only.
    When present it must be a JSON object of the form
    {"forbidden_patterns": ["...", "..."]}; a malformed file is a build error
    rather than a silent downgrade of the scan.
    """
    if not LOCAL_SCAN_FILE.is_file():
        return []
    try:
        payload = json.loads(LOCAL_SCAN_FILE.read_text(encoding='utf-8'))
    except (OSError, ValueError) as exc:
        raise SystemExit(f'build error: could not read {LOCAL_SCAN_LABEL}: {exc}')
    patterns = payload.get('forbidden_patterns') if isinstance(payload, dict) else None
    if not isinstance(patterns, list) or not all(isinstance(item, str) and item for item in patterns):
        raise SystemExit(f'build error: {LOCAL_SCAN_LABEL} must be '
                         '{"forbidden_patterns": ["non-empty string", ...]}')
    return patterns


def scan_text(name, text, extra_patterns=()):
    """Return [(name, lineno, display, line)] for every forbidden hit.

    Literal prefixes (generic plus optional local additions) are matched as plain
    substrings; shaped credential prefixes (FORBIDDEN_REGEXES) are matched as
    exact regexes.
    """
    literals = list(FORBIDDEN_PATTERNS) + list(extra_patterns)
    hits = []
    for lineno, line in enumerate(text.splitlines(), 1):
        for literal in literals:
            if literal in line:
                hits.append((name, lineno, repr(literal), line.strip()))
        for label, regex in FORBIDDEN_REGEXES:
            if regex.search(line):
                hits.append((name, lineno, label, line.strip()))
    return hits


def run(cmd, cwd):
    """Run a child process with sys.executable; capture merged output."""
    proc = subprocess.run(cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          text=True, encoding='utf-8', errors='replace')
    return proc.returncode, proc.stdout or ''


def indent(text, prefix='      '):
    lines = text.strip().splitlines() or ['']
    return '\n'.join(prefix + line for line in lines)


def run_self_check(zip_path, required, top_dir, extra_patterns=()):
    """Run checks a-j and return a list of human-readable failure strings."""
    failures = []

    with zipfile.ZipFile(zip_path) as archive:
        names = [n for n in archive.namelist() if not n.endswith('/')]
    packaged = [n[len(top_dir) + 1:] for n in names if n.startswith(top_dir + '/')]

    # (a) packaged file set == REQUIRED + MANIFEST.json
    expected_set = set(required) | {MANIFEST_NAME}
    packaged_set = set(packaged)
    missing = sorted(expected_set - packaged_set)
    extra = sorted(packaged_set - expected_set)
    if missing:
        failures.append(f'(a) package is missing REQUIRED files: {", ".join(missing)}')
    if extra:
        failures.append(f'(a) package contains files not in REQUIRED + {MANIFEST_NAME}: '
                        f'{", ".join(extra)}')
    if len(packaged) != len(expected_set):
        failures.append(f'(a) package file count {len(packaged)} != '
                        f'REQUIRED + {MANIFEST_NAME} count {len(expected_set)}')

    # (f, structural) forbidden path segments / files
    for rel in sorted(packaged):
        if FORBIDDEN_SEGMENTS.intersection(rel.split('/')):
            failures.append(f'(f) forbidden path segment inside package: {rel}')
        if rel in FORBIDDEN_PATHS:
            failures.append(f'(f) forbidden file inside package: {rel}')

    with tempfile.TemporaryDirectory() as tmp:
        pkg_root = Path(tmp) / top_dir
        with zipfile.ZipFile(zip_path) as archive:
            archive.extractall(tmp)

        # (a) the shipped manifest must resolve every path, match every hash and
        # size, use only legal categories, and list exactly the REQUIRED set.
        manifest_path = pkg_root / MANIFEST_NAME
        if not manifest_path.is_file():
            failures.append(f'(a) package is missing {MANIFEST_NAME}')
        else:
            try:
                manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
            except ValueError as exc:
                failures.append(f'(a) {MANIFEST_NAME} is not valid JSON: {exc}')
            else:
                for reason in check_drift.validate_manifest(pkg_root, manifest):
                    failures.append(f'(a) {MANIFEST_NAME}: {reason}')
                listed = [entry.get('path') for entry in manifest.get('files', [])
                          if isinstance(entry, dict)]
                if sorted(listed) != sorted(required):
                    failures.append(f'(a) {MANIFEST_NAME} paths do not match the REQUIRED list')

        # (b) validate_kit.py passes in the extracted package
        rc, out = run([sys.executable, str(pkg_root / 'scripts' / 'validate_kit.py')], pkg_root)
        if rc != 0:
            failures.append(f'(b) validate_kit.py failed inside package (exit {rc}):\n{indent(out)}')

        # (c) validate_kit.py --project-ready must FAIL with a FILL_IN mention
        rc, out = run([sys.executable, str(pkg_root / 'scripts' / 'validate_kit.py'), '--project-ready'], pkg_root)
        if rc == 0:
            failures.append('(c) validate_kit.py --project-ready unexpectedly PASSED; '
                            'docs/PROJECT.md was not shipped (by design); FILL_IN guidance missing')
        elif 'FILL_IN' not in out:
            failures.append('(c) validate_kit.py --project-ready failed but output never mentions '
                            f'FILL_IN:\n{indent(out)}')

        # (d) unit tests pass in the extracted package
        rc, out = run([sys.executable, '-m', 'unittest', 'discover', '-s', 'tests'], pkg_root)
        if rc != 0:
            failures.append(f'(d) unit tests failed inside package (exit {rc}):\n{indent(out)}')

        # (e) orchestrator smoke: init then task list
        rc, out = run([sys.executable, str(pkg_root / 'scripts' / 'orchestrator.py'), 'init'], pkg_root)
        if rc != 0:
            failures.append(f'(e) orchestrator.py init failed inside package (exit {rc}):\n{indent(out)}')
        rc, out = run([sys.executable, str(pkg_root / 'scripts' / 'orchestrator.py'), 'task', 'list'], pkg_root)
        if rc != 0:
            failures.append(f'(e) orchestrator.py task list failed inside package (exit {rc}):\n{indent(out)}')

        # (f) non-essential information scan over every text file
        for rel in sorted(packaged):
            data = (pkg_root / rel).read_bytes()
            if b'\x00' in data:
                continue  # skip binary payloads
            text = data.decode('utf-8', errors='replace')
            for name, lineno, display, line in scan_text(rel, text, extra_patterns):
                failures.append(f'(f) {name}:{lineno}: forbidden pattern {display}: {line}')

        # (h) the optional architecture checker must import and degrade to
        # diagnostic mode inside a package that carries no contract (docs/ is
        # never packaged). A non-zero exit, a guessed ENFORCE mode or a report
        # without a bound head_sha would mean the shipped checker lies about
        # what it checked.
        checker = pkg_root / 'scripts' / 'architecture' / 'check.py'
        rc, out = run([sys.executable, str(checker), '--project', str(pkg_root), '--json'],
                      pkg_root)
        if rc != 0:
            failures.append(f'(h) architecture checker failed inside package (exit {rc}):\n'
                            f'{indent(out)}')
        else:
            try:
                architecture_report = json.loads(out)
            except ValueError as exc:
                failures.append(f'(h) architecture checker emitted no JSON report: {exc}')
            else:
                if architecture_report.get('enforcement_mode') != 'OFF':
                    failures.append('(h) architecture checker must run in OFF without a contract, '
                                    f'got {architecture_report.get("enforcement_mode")!r}')
                if architecture_report.get('blocking'):
                    failures.append('(h) architecture checker blocked a contract-less package')
                if 'head_sha' not in architecture_report \
                        or architecture_report.get('head_sha_source') != 'unavailable':
                    failures.append('(h) architecture checker report does not bind head_sha '
                                    '(expected an explicit "unavailable" inside the extracted zip)')

        # (i) the natural-language update entry must import and expose its help
        # inside a package that carries no docs/. A missing package module would
        # otherwise only surface when a downstream user tries the trigger.
        rc, out = run([sys.executable, '-m', 'scripts.update_agentorch.entry', '--help'],
                      pkg_root)
        if rc != 0:
            failures.append(f'(i) update entry failed inside package (exit {rc}):\n{indent(out)}')
        elif 'update_agentorch.entry' not in out:
            failures.append('(i) update entry help does not identify the entry point:\n'
                            f'{indent(out)}')

        # (j) the shipped self-improvement registry example must be one the
        # shipped validator accepts. This keeps the in-package operating note and
        # the schema from drifting apart after docs/ is stripped.
        probe = (
            'import json\n'
            'from scripts.self_improvement import sources\n'
            "with open('templates/self-improvement/sources.example.json', encoding='utf-8') as fh:\n"
            '    data = json.load(fh)\n'
            'errors = sources.validate_registry(data)\n'
            'if errors:\n'
            "    print(errors)\n"
            '    raise SystemExit(1)\n'
        )
        rc, out = run([sys.executable, '-c', probe], pkg_root)
        if rc != 0:
            failures.append('(j) sources.example.json is not a valid registry inside the '
                            f'package (exit {rc}):\n{indent(out)}')

        # (k) the synthetic delivery scenarios must all pass inside the package.
        # A negative scenario passing means its gate really fired; the report must
        # carry `errors: 0`, `negative_passed == negative` and at least one passing
        # positive control, so "everything failed" or "a gate did not fire" cannot
        # hide behind an exit code alone.
        rc, out = run([sys.executable, str(pkg_root / 'scripts' / 'run_delivery_scenarios.py'),
                       '--json'], pkg_root)
        if rc != 0:
            failures.append(f'(k) delivery scenarios failed inside package (exit {rc}):\n'
                            f'{indent(out)}')
        else:
            try:
                scenario_report = json.loads(out)
            except ValueError as exc:
                failures.append(f'(k) delivery scenarios emitted no JSON report: {exc}')
            else:
                totals = scenario_report.get('totals') or {}
                if not scenario_report.get('scenarios'):
                    failures.append('(k) delivery scenario report lists no scenarios')
                if totals.get('errors'):
                    failures.append(f'(k) {totals["errors"]} scenario(s) errored')
                if totals.get('failed'):
                    failures.append(f'(k) {totals["failed"]} scenario(s) failed')
                if totals.get('negative_passed') != totals.get('negative'):
                    failures.append('(k) not every negative scenario passed: its gate did not '
                                    f'fire ({totals.get("negative_passed")}/'
                                    f'{totals.get("negative")})')
                if not totals.get('positive_passed'):
                    failures.append('(k) no positive control passed, so "all scenarios fail" '
                                    'cannot be excluded')

        # (l) the metric report must reproduce the documented gold sample and must
        # report an empty input as `no data` (never 0). Both runs are read-only and
        # use the sample embedded in the shipped templates/metrics.md.
        rc, out = run([sys.executable, str(pkg_root / 'scripts' / 'report_metrics.py'),
                       '--gold-sample', '--since', '2026-01-01', '--until', '2026-02-01',
                       '--json'], pkg_root)
        if rc != 0:
            failures.append(f'(l) metric gold sample failed inside package (exit {rc}):\n'
                            f'{indent(out)}')
        else:
            try:
                metric_report = json.loads(out)
            except ValueError as exc:
                failures.append(f'(l) metric report emitted no JSON: {exc}')
            else:
                metrics = metric_report.get('metrics') or []
                if len(metrics) != 7:
                    failures.append(f'(l) expected seven metrics, got {len(metrics)}')
                if not metric_report.get('window', {}).get('start'):
                    failures.append('(l) metric report carries no explicit window start')
                for metric in metrics:
                    for key in ('sample_size', 'eligible', 'missing', 'missing_rate',
                                'coverage'):
                        if key not in metric:
                            failures.append(f'(l) metric {metric.get("id")} is missing {key}')
                if metric_report.get('summary', {}).get('headline') == 'no data':
                    failures.append('(l) the gold sample produced no data')
        empty_fixture = Path(tmp) / 'empty-events.json'
        empty_fixture.write_text('{"events": []}', encoding='utf-8')
        rc, out = run([sys.executable, str(pkg_root / 'scripts' / 'report_metrics.py'),
                       str(empty_fixture), '--since', '2026-01-01', '--until', '2026-02-01',
                       '--json'], pkg_root)
        if rc != 0:
            failures.append(f'(l) metric empty-input report failed inside package '
                            f'(exit {rc}):\n{indent(out)}')
        else:
            try:
                empty_report = json.loads(out)
            except ValueError as exc:
                failures.append(f'(l) empty-input metric report emitted no JSON: {exc}')
            else:
                if empty_report.get('summary', {}).get('headline') != 'no data':
                    failures.append('(l) an empty input was not reported as "no data"')

        # (f) line-ending assertion: no packaged *text* file may contain CRLF.
        # Text is the same rule normalize_line_endings() uses (no NUL byte and
        # valid UTF-8); binary payloads ship verbatim and are exempt. A CRLF here
        # means normalization missed a file, so archives built from different
        # checkout states would no longer be byte-identical.
        for rel in sorted(packaged):
            data = (pkg_root / rel).read_bytes()
            if not is_text(data):
                continue
            if b'\r\n' in data:
                failures.append(f'(f) line-ending: packaged text file contains CRLF: {rel}')

    return failures


def sha256_file(path):
    digest = hashlib.sha256()
    with path.open('rb') as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b''):
            digest.update(chunk)
    return digest.hexdigest()


def release_asset_stem(date_stamp=None, release_version=None):
    """Return the asset stem, which is also the archive's top-level directory.

    Exactly one naming mode is allowed. `release_version` names a public release
    (`1.6` -> `AgentOrch-1.6`, so `AgentOrch-1.6.zip` with a single top-level
    directory `AgentOrch-1.6/`); otherwise the default date naming applies
    (`agentorch-YYYYMMDD`). Passing both is an error: there is no precedence rule
    to remember, and neither flag may silently override the other.
    """
    if release_version is not None and date_stamp is not None:
        raise SystemExit('build error: --release-version and --date are mutually exclusive; '
                         'omit --date when building a named release asset')
    if release_version is not None:
        if not RELEASE_VERSION_RE.fullmatch(release_version):
            raise SystemExit('build error: --release-version must look like 1.6 (or 1.6.1), '
                             f"without a 'v' prefix or prerelease suffix, got {release_version!r}")
        return f'{RELEASE_ASSET_PREFIX}{release_version}'
    stamp = date_stamp if date_stamp is not None else date.today().strftime('%Y%m%d')
    if not DATE_STAMP_RE.fullmatch(stamp):
        raise SystemExit(f'build error: --date must be YYYYMMDD, got {stamp!r}')
    return f'{DATE_ASSET_PREFIX}{stamp}'


def main():
    parser = argparse.ArgumentParser(description='Build the generic Agent-Orchestration release zip.')
    naming = parser.add_mutually_exclusive_group()
    naming.add_argument('--date', default=None,
                        help='date naming as YYYYMMDD, producing agentorch-YYYYMMDD.zip '
                             '(default: today; cannot be combined with --release-version)')
    naming.add_argument('--release-version', default=None, metavar='X.Y',
                        help='public release naming, e.g. 1.6, producing AgentOrch-1.6.zip '
                             '(cannot be combined with --date)')
    parser.add_argument('--output-dir', default=DEFAULT_OUTPUT_DIR,
                        help='directory that receives the zip (default: release/)')
    args = parser.parse_args()

    # Validate the naming before any read / packaging work so a bad flag fails
    # fast and never leaves a half-built artifact behind.
    top_dir = release_asset_stem(args.date, args.release_version)

    required = read_required()
    files = collect_sources(required)
    suite, format_version = check_drift.read_version(ROOT)
    manifest = check_drift.build_manifest(files, suite, format_version)
    files[MANIFEST_NAME] = check_drift.dumps_manifest(manifest).encode('utf-8')
    extra_patterns = load_extra_patterns()
    print(f'extra scan patterns: {len(extra_patterns)} (from {LOCAL_SCAN_LABEL})'
          if extra_patterns else 'extra scan patterns: none')

    zip_path = Path(args.output_dir) / f'{top_dir}.zip'

    write_zip(zip_path, files, top_dir)
    failures = run_self_check(zip_path, required, top_dir, extra_patterns)

    if failures:
        print('RELEASE SELF-CHECK FAILED')
        for reason in failures:
            print(f'- {reason}')
        # Never leave an artifact that failed self-check in the output directory:
        # it would be easy to mistake for a release. Remove it and say so.
        try:
            zip_path.unlink()
            print(f'- deleted the artifact that failed self-check: {zip_path}')
        except OSError as exc:
            print(f'- could not delete the failed artifact, still present at: {zip_path} ({exc})')
        return 1

    size = zip_path.stat().st_size
    sha256 = sha256_file(zip_path)
    print('Release self-check passed (checks a-l).')
    print(f'  package files : {len(files)} ({len(required)} REQUIRED + {MANIFEST_NAME})')
    print(f'  manifest      : schema {manifest["schema_version"]}, suite {manifest["suite"]!r}, '
          f'format {manifest["format_version"]}')
    print(f'  zip path      : {zip_path}')
    print(f'  zip size      : {size} bytes')
    print(f'  zip sha256    : {sha256}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
